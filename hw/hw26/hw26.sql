--     Задание 5. Найдите количество продаж каждого товара (название товара, кол-во заказов).
    SELECT p.id,
           p.title,
           COALESCE(
                   sum(o.quantity),
                   0) AS sold_count
    FROM orders o
    RIGHT JOIN products p ON o.product_id = p.id
    GROUP BY p.id, p.title
    ORDER BY sold_count DESC;

--     Задание 6. Найдите общую сумму каждого заказа (подсказка: quantity * price). Результат: ID заказа, клиент, товар, итоговая сумма.
    SELECT o.id AS order_id,
           c.full_name AS client_name,
           COALESCE(
                   round(
                           (o.quantity * p.price)::NUMERIC,
                           2),
                   0) AS total_sold_sum
    FROM orders o
    JOIN products p ON o.product_id = p.id
    JOIN customer c ON o.customer_id = c.id
    GROUP BY o.id, c.full_name, p.price
    ORDER BY o.id;

--     Задание 7. Найдите общую сумму покупок для каждого клиента (клиент, общая сумма потраченных денег).
    SELECT c.full_name AS client_name,
           COALESCE(
                   ROUND(
                           SUM((o.quantity * p.price)::NUMERIC),
                           2),
                   0) total_spent_sum
    FROM customer c
    LEFT JOIN orders o ON c.id = o.customer_id
    LEFT JOIN products p ON o.product_id = p.id
    GROUP BY c.id
    ORDER BY total_spent_sum DESC;


