    id SERIAL PRIMARY KEY,
    customer_id INT,
    product_id INT,
    quantity INT CHECK (quantity > 0),
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),

    FOREIGN KEY (customer_id)
                    REFERENCES customer(id),
    FOREIGN KEY (product_id)
                    REFERENCES products(id)
);

