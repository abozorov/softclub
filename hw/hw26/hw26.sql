           COALESCE(
                   round(
                           sum(o.quantity * p.price)::NUMERIC,
                           2),
                   0) AS total_byed_sum,
           COALESCE(
                   avg(o.quantity * p.price),
                   0) AS average_cost
    FROM customer c
    LEFT JOIN orders o on c.id = o.customer_id
    LEFT JOIN products p on o.product_id = p.id
    GROUP BY c.id
    ORDER BY total_byed_sum DESC;